using System.Text;
using CS2Browser.IdlGenerator.Model;

namespace CS2Browser.IdlGenerator.Generation;

/// <summary>
/// 파싱된 IDL 모듈로부터 ClearScript(<c>ScriptMember</c>) 규격의 C# 브릿지 클래스를 생성한다.
/// 알려진 멤버는 <see cref="StaticBindingMap"/> 을 통해 AngleSharp API 로 직접 연결하고,
/// 나머지는 런타임 디스패처로 위임한다.
/// </summary>
public sealed class CSharpEmitter
{
    private readonly string _namespace;
    private readonly IdlModule _module;
    private readonly HashSet<string> _interfaceNames;

    public CSharpEmitter(IdlModule module, string @namespace = "CS2Browser.Scripting.Generated")
    {
        _module = module;
        _namespace = @namespace;
        _interfaceNames = new HashSet<string>(module.Interfaces.Select(i => i.Name), StringComparer.Ordinal);
    }

    /// <summary>인터페이스별 생성 파일(파일명 → 소스)을 반환한다.</summary>
    public IReadOnlyDictionary<string, string> EmitAll()
    {
        var files = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var iface in _module.Interfaces)
        {
            if (iface.IsMixin)
            {
                continue;
            }

            files[iface.Name + ".g.cs"] = EmitInterface(iface);
        }

        return files;
    }

    public string EmitInterface(IdlInterface iface)
    {
        var className = NameMapper.ToPascal(iface.Name) + "Bridge";
        var baseClass = ResolveBaseClass(iface);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//   이 파일은 CS2Browser.IdlGenerator 가 Web IDL 로부터 자동 생성했습니다. 직접 수정하지 마세요.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using CS2Browser.Scripting;");
        sb.AppendLine("using Microsoft.ClearScript;");
        sb.AppendLine("using Microsoft.ClearScript.V8;");
        sb.AppendLine();
        sb.AppendLine($"namespace {_namespace};");
        sb.AppendLine();
        sb.AppendLine("[NoDefaultScriptAccess]");
        sb.AppendLine($"public class {className} : {baseClass}");
        sb.AppendLine("{");
        sb.AppendLine($"    public {className}(object target, V8ScriptEngine engine)");
        sb.AppendLine("        : base(target, engine)");
        sb.AppendLine("    {");
        sb.AppendLine("    }");

        foreach (var constant in iface.Constants)
        {
            EmitConstant(sb, constant);
        }

        foreach (var attribute in iface.Attributes)
        {
            EmitAttribute(sb, iface, attribute);
        }

        foreach (var operation in iface.Operations)
        {
            if (string.Equals(operation.Name, "constructor", StringComparison.Ordinal))
            {
                continue;
            }

            EmitOperation(sb, iface, operation);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private string ResolveBaseClass(IdlInterface iface)
    {
        if (iface.Inheritance is not null && _interfaceNames.Contains(iface.Inheritance) && !iface.IsMixin)
        {
            return NameMapper.ToPascal(iface.Inheritance) + "Bridge";
        }

        return "DomBridgeBase";
    }

    private static void EmitConstant(StringBuilder sb, IdlConstant constant)
    {
        var type = TypeMapper.Map(constant.Type);
        sb.AppendLine();
        sb.AppendLine($"    public const {type} {constant.Name} = {constant.Value};");
    }

    private void EmitAttribute(StringBuilder sb, IdlInterface iface, IdlAttribute attribute)
    {
        var memberName = NameMapper.Escape(NameMapper.ToPascal(attribute.Name));
        sb.AppendLine();

        if (StaticBindingMap.TryGet(iface.Name, attribute.Name, out var binding) && binding.Kind == StaticKind.Property)
        {
            sb.AppendLine($"    [ScriptMember(\"{attribute.Name}\")]");
            sb.AppendLine($"    public {binding.ReturnType} {memberName}");
            sb.AppendLine("    {");
            sb.AppendLine($"        get => {binding.Body};");
            if (!attribute.Readonly && binding.SetBody is not null)
            {
                sb.AppendLine($"        set => {binding.SetBody}");
            }

            sb.AppendLine("    }");
            return;
        }

        // 런타임 디스패처.
        sb.AppendLine($"    [ScriptMember(\"{attribute.Name}\")]");
        sb.AppendLine($"    public object? {memberName}");
        sb.AppendLine("    {");
        sb.AppendLine($"        get => Get(\"{attribute.Name}\");");
        if (!attribute.Readonly)
        {
            sb.AppendLine($"        set => Set(\"{attribute.Name}\", value);");
        }

        sb.AppendLine("    }");
    }

    private void EmitOperation(StringBuilder sb, IdlInterface iface, IdlOperation operation)
    {
        var memberName = NameMapper.Escape(NameMapper.ToPascal(operation.Name));
        sb.AppendLine();

        if (StaticBindingMap.TryGet(iface.Name, operation.Name, out var binding)
            && binding.Kind == StaticKind.Method
            && binding.Parameters is { Length: > 0 } parameters
            && parameters.Length == operation.Arguments.Count)
        {
            var typedParams = string.Join(", ", operation.Arguments.Select((arg, i) =>
                TypedParam(arg, parameters[i])));
            sb.AppendLine($"    [ScriptMember(\"{operation.Name}\")]");
            if (string.Equals(binding.ReturnType, "void", StringComparison.Ordinal))
            {
                sb.AppendLine($"    public void {memberName}({typedParams})");
                sb.AppendLine("    {");
                sb.AppendLine($"        {binding.Body}");
                sb.AppendLine("    }");
            }
            else
            {
                sb.AppendLine($"    public {binding.ReturnType} {memberName}({typedParams}) => {binding.Body};");
            }

            return;
        }

        // 런타임 디스패처.
        var args = operation.Arguments;
        var paramList = string.Join(", ", args.Select(a =>
        {
            var name = NameMapper.Escape(a.Name);
            return a.Variadic ? $"params object?[] {name}" : $"object? {name} = null";
        }));
        var callArgs = string.Join(", ", args.Select(a => NameMapper.Escape(a.Name)));
        var call = string.IsNullOrEmpty(callArgs)
            ? $"Call(\"{operation.Name}\")"
            : $"Call(\"{operation.Name}\", {callArgs})";

        sb.AppendLine($"    [ScriptMember(\"{operation.Name}\")]");
        sb.AppendLine($"    public object? {memberName}({paramList})");
        sb.AppendLine($"        => {call};");
    }

    private static string ParamType(IdlType type)
        => TypeMapper.IsDomNodeType(type) ? "object?" : TypeMapper.Map(type);

    private static string TypedParam(IdlArgument arg, string name)
    {
        var type = ParamType(arg.Type);
        var escaped = NameMapper.Escape(name);
        if (!arg.Optional)
        {
            return $"{type} {escaped}";
        }

        if (TypeMapper.IsValueType(type.TrimEnd('?')))
        {
            return $"{type} {escaped} = default";
        }

        return $"{(type.EndsWith('?') ? type : type + "?")} {escaped} = null";
    }
}
